"""CQL2 expression cases from cartosym-draft-check.

`tests/data/cartosym_draft_cases.json` holds the expression test cases that
cartosym-draft-check (https://github.com/henrik716/cartosym-draft-check, MIT)
uses to check the draft requirements of OGC Cartographic Symbology 2.0
(opengeospatial/cartographic-symbology#133). They are generated by
`tools/export_pycartosym_cases.py` there; change the cases in that repository
and export them again, not here.

Only what pycartosym owns is tested: CQL2-Text → CQL2-JSON and the
CQL2-JSON → CQL2-Text → CQL2-JSON round trip for the cases with an expected
CQL2-JSON, and that the others parse. What the draft says an expression
evaluates to stays in cartosym-draft-check. A case whose draft wording is
still open in the PR is `xfail(strict=False)`, so a choice of the SWG does
not block CI.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import pytest

from pycartosym import cql2

_DATA = Path(__file__).parent / "data" / "cartosym_draft_cases.json"
_CASES: list[dict[str, Any]] = json.loads(_DATA.read_text(encoding="utf-8"))["cases"]


def _params(cases: Iterable[dict[str, Any]]) -> list[Any]:
    return [
        pytest.param(
            case,
            id=case["id"],
            marks=(
                [pytest.mark.xfail(reason=case["disputed"], strict=False)]
                if "disputed" in case
                else []
            ),
        )
        for case in cases
    ]


_WITH_JSON = _params(case for case in _CASES if "json" in case)
_TEXT_ONLY = _params(case for case in _CASES if "json" not in case)


@pytest.mark.parametrize("case", _WITH_JSON)
def test_text_to_json(case: dict[str, Any]) -> None:
    assert cql2.to_cql2_json(cql2.parse_text(case["text"])) == case["json"]


@pytest.mark.parametrize("case", _WITH_JSON)
def test_json_round_trip(case: dict[str, Any]) -> None:
    text = cql2.to_cql2_text(case["json"])
    assert cql2.to_cql2_json(cql2.parse_text(text)) == case["json"], text


@pytest.mark.parametrize("case", _TEXT_ONLY)
def test_text_parses(case: dict[str, Any]) -> None:
    cql2.parse_text(case["text"])
